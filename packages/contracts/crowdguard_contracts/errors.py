"""Stable client-facing error codes. Messages are safe; details stay in server logs."""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, Optional

from pydantic import BaseModel, ConfigDict


class ErrorCode(str, Enum):
    VALIDATION_ERROR = "VALIDATION_ERROR"
    NOT_FOUND = "NOT_FOUND"
    INVALID_STATE = "INVALID_STATE"
    QUOTA_EXCEEDED = "QUOTA_EXCEEDED"
    RATE_LIMITED = "RATE_LIMITED"
    UPLOAD_TOO_LARGE = "UPLOAD_TOO_LARGE"
    UPLOAD_TOO_MANY_PARTS = "UPLOAD_TOO_MANY_PARTS"
    UPLOAD_TYPE_NOT_ALLOWED = "UPLOAD_TYPE_NOT_ALLOWED"
    UPLOAD_PART_INVALID = "UPLOAD_PART_INVALID"
    UPLOAD_PART_MISMATCH = "UPLOAD_PART_MISMATCH"
    UPLOAD_SIZE_MISMATCH = "UPLOAD_SIZE_MISMATCH"
    UPLOAD_EXPIRED = "UPLOAD_EXPIRED"
    UPLOAD_STORAGE_ERROR = "UPLOAD_STORAGE_ERROR"
    UPLOAD_REJECTED_FORMAT = "UPLOAD_REJECTED_FORMAT"
    UPLOAD_REJECTED_DURATION = "UPLOAD_REJECTED_DURATION"
    UPLOAD_REJECTED_RESOLUTION = "UPLOAD_REJECTED_RESOLUTION"
    UPLOAD_REJECTED_CORRUPT = "UPLOAD_REJECTED_CORRUPT"
    ZONE_CONFIG_INVALID = "ZONE_CONFIG_INVALID"
    POLICY_UNAVAILABLE = "POLICY_UNAVAILABLE"
    POLICY_INCOMPLETE = "POLICY_INCOMPLETE"
    PROCESSING_FAILED = "PROCESSING_FAILED"
    ENCODE_FAILED = "ENCODE_FAILED"
    OUTPUT_UPLOAD_FAILED = "OUTPUT_UPLOAD_FAILED"
    WORKER_LEASE_EXPIRED = "WORKER_LEASE_EXPIRED"
    JOB_TIMEOUT = "JOB_TIMEOUT"


class ApiError(BaseModel):
    model_config = ConfigDict(extra="forbid")
    code: ErrorCode
    message: str
    details: Optional[Dict[str, Any]] = None
